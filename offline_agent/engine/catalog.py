"""
engine/catalog.py: capability cards. What every agent and every tool does, in plain words.

Cards are built FROM THE CODE (template fields, permissions, tool descriptions), so they can't
drift out of date. They appear in the Studio, on the Catalog page, in `offline-agent info`,
and in docs/CATALOG.md (generated by `offline-agent catalog --write`).
"""
import inspect
import json

from .config import TEMPLATES_DIR, list_configs, load_agent
from .permissions import ALLOW, ASK, CAPABILITIES, OFF, cap_title
from .planner import capabilities_summary
from .tools import TOOLS, is_internal, tools_for

MODE_TEXT = {"agent": "Agent: the model works step by step with tools",
             "rules": "Clerk: the model writes one rule, you approve it, code does the work and checks it"}


def needs_in_words(cfg):
    """'Reads and moves files in a folder you choose. Asks before every move. No internet.'"""
    pol, said = cfg.permissions, []
    on = lambda c: pol.mode(c) != OFF  # noqa: E731
    files = [CAPABILITIES[f"files.{a}"]["label"].lower() for a in ("read", "create", "modify", "move", "delete")
             if on(f"files.{a}")]
    if files:
        where = ("a folder you choose" if not pol.files.folders else
                 ", ".join("the workspace" if f == "workspace" else f for f in pol.files.folders))
        said.append(f"Files: {', '.join(files)} in {where}.")
        asks = [CAPABILITIES[f"files.{a}"]["label"].lower() for a in ("create", "modify", "move", "delete")
                if pol.mode(f"files.{a}") == ASK]
        if asks:
            said.append(f"Asks before: {', '.join(asks)}.")
    web = [x for x in ("read", "search") if on(f"internet.{x}")]
    said.append(("Internet: " + " and ".join("reads pages" if x == "read" else "searches DuckDuckGo" for x in web)
                 + (f" on {', '.join(pol.internet.domains)}" if pol.internet.domains and "read" in web else "") + ".")
                if web else "No internet.")
    if on("email.read") or on("email.organize"):
        said.append("Email: reads" + (" and organizes" if on("email.organize") else "")
                    + (" (asks first)" if pol.mode("email.organize") == ASK else "") + ". Never sends or deletes.")
    if on("memory.read") or on("memory.write"):
        said.append("Memory: " + " and ".join(x for x, c in (("recalls", "memory.read"), ("saves notes", "memory.write"))
                                              if on(c)) + ".")
    if on("interaction.ask_user"):
        said.append("Can ask you questions during a run.")
    return " ".join(said)


def agent_card(cfg, bench=None):
    """Everything a person needs to know before using an agent."""
    allowed, asks, off, notes = capabilities_summary(cfg)
    return {
        "name": cfg.name, "what": cfg.description or "(no description)",
        "good_for": cfg.good_for, "not_for": cfg.not_for, "examples": cfg.examples,
        "needs": needs_in_words(cfg), "mode": MODE_TEXT.get(cfg.mode, cfg.mode), "model": cfg.model,
        "tools": [t for t in tools_for(cfg)],
        "extras": [x for x, on in (("Job notes", cfg.plan_steps and cfg.mode == "agent"),
                                   ("Inspector (verifier)", cfg.verify.enabled and cfg.mode == "agent"),
                                   ("Telegram style", cfg.terse), ("Full Voice", cfg.full_voice)) if on],
        "tested": bench,
    }


def tool_card(name):
    t = TOOLS[name]
    fn, schema = t["function"], t["schema"]["function"]
    sig = inspect.signature(fn)
    args = []
    for arg, p in sig.parameters.items():
        prop = schema["parameters"]["properties"].get(arg, {})
        default = None if p.default is inspect.Parameter.empty else p.default
        args.append({"name": arg, "type": prop.get("type", "string"), "required": default is None,
                     "default": default, "about": prop.get("description", "")})
    cap = t["permission"]
    unlocked = ("always available" if cap is None else
                "framework tool (job notes)" if is_internal(name) else cap_title(cap))
    return {"name": name, "what": schema["description"], "unlocked_by": unlocked, "args": args,
            "safety": t.get("safety", ""), "example": t.get("example", "")}


def all_tool_cards(include_internal=True):
    return [tool_card(n) for n in TOOLS if include_internal or not is_internal(n)]


# ---------------------------------------------------------------- text versions

def agent_markdown(card, heading="###"):
    out = [f"{heading} {card['name']}", "", card["what"], ""]
    if card["good_for"]:
        out += ["**Good for:** " + " · ".join(card["good_for"])]
    if card["not_for"]:
        out += ["**Not for:** " + " · ".join(card["not_for"])]
    out += [f"**Needs:** {card['needs']}", f"**How it works:** {card['mode']}"]
    if card["extras"]:
        out += ["**Features:** " + " · ".join(card["extras"])]
    out += ["**Tools:** " + ", ".join(f"`{t}`" for t in card["tools"])]
    if card["examples"]:
        out += ["", "**Try:**"] + [f"- {e}" for e in card["examples"]]
    if card.get("tested"):
        out += ["", f"**Tested:** {card['tested']}"]
    return "\n".join(out) + "\n"


def tool_markdown(card, heading="###"):
    out = [f"{heading} `{card['name']}`", "", card["what"], "", f"**Unlocked by:** {card['unlocked_by']}"]
    if card["args"]:
        out += ["", "| Input | Type | Required | About |", "|---|---|---|---|"]
        for a in card["args"]:
            req = "yes" if a["required"] else f"no (default `{json.dumps(a['default'])}`)"
            out.append(f"| `{a['name']}` | {a['type']} | {req} | {a['about']} |")
    if card["safety"]:
        out += ["", f"**Safety:** {card['safety']}"]
    if card["example"]:
        out += ["", "**Example output:**", "```", card["example"], "```"]
    return "\n".join(out) + "\n"


def catalog_markdown():
    """docs/CATALOG.md: every built-in agent and every tool. Generated; don't edit by hand."""
    agents = [agent_card(load_agent(p)) for p in list_configs(TEMPLATES_DIR).values()]
    groups = {}
    for c in all_tool_cards():
        groups.setdefault(c["unlocked_by"].split(":")[0], []).append(c)
    out = ["# Catalog", "",
           "_Generated from the code by `offline-agent catalog --write`. Don't edit by hand._", "",
           "Every built-in agent (template) and every tool, in plain words.", "",
           "## Agents", "", "| Agent | What it does | How it works |", "|---|---|---|"]
    for a in agents:
        out.append(f"| [{a['name']}](#{a['name'].lower().replace(' ', '-')}) | {a['what']} | "
                   f"{a['mode'].split(':')[0]} |")
    out.append("")
    out += [agent_markdown(a) for a in agents]
    out += ["## Tools", "", "Tools are unlocked by an agent's permissions (Off / Allow / Ask first).", ""]
    for group, cards in groups.items():
        out += [f"### {group}", ""] + [tool_markdown(c, "####") for c in cards]
    return "\n".join(out)


def find(name):
    """An agent (by name or file) or a tool (by name) for `offline-agent info`."""
    key = str(name).strip().lower().replace("-", "_").removesuffix(".yaml")
    if key in TOOLS:
        return "tool", tool_card(key)
    from .bench import available_agents
    for label, path in available_agents().items():
        if key in (label.lower(), label.lower().replace(" ", "_"), path.stem.lower()):
            return "agent", agent_card(load_agent(path), latest_bench(label))
    return None, None


def latest_bench(agent_name):
    """'✅ passed on qwen3.5:9b (Telegram on), 89s, 2026-10-22' from the newest Test Bench report."""
    from .bench import past_reports
    for report in past_reports():
        try:
            data = json.loads(report.read_text(encoding="utf-8"))
        except Exception:
            continue
        rows = [r for r in data.get("results", []) if r["agent"] == agent_name and r.get("passed") is not None]
        if rows:
            r = rows[0]
            mark = "✅ passed" if r["passed"] else "❌ failed"
            return f"{mark} on {r['model']} ({r['variant']}), {r.get('seconds', '?')}s, {data['id'][:8]}"
    return None
